// The trigonometry tests that came before this one compared against std::sin and std::cos with a
// 1e-10 tolerance. That cannot see past double precision, which is how the multi-component types
// shipped for so long delivering double-double accuracy no matter how many limbs they carried
// (universal#1318): qd reached 43 of its 63 digits, td_cascade and qd_cascade 32 of 48 and 63.
//
// So this suite scores each type against a reference wider than any format under test. The
// reference values are carried as six doubles (~318 bits), generated by mpmath at 200 decimal
// digits (tools/generators/cascade_trig_gen.py). Both the reference and the computed value are
// exact sums of doubles, so both convert exactly to dyadic rationals and the verdict
// |computed - reference| <= 2^-budget * |reference| is decided in exact integer arithmetic -- no
// floating-point arithmetic sits between the implementation and its score.
//
// All six functions are covered, because the defect had two independent causes and the second one
// only showed up in the inverse functions: sin and cos truncated their Taylor series at a
// double-double threshold, while atan2 -- which atan, asin and acos all route through -- took a
// single Newton step, doubling the seed's 53 bits exactly once.
