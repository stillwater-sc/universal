// dd, qd, dd_cascade, td_cascade and qd_cascade each carry a table of constants (pi, e, ln 2,
// sqrt 2, ...) as a few doubles. A table entry is right when it is the nearest expansion of the
// constant: c0 the double nearest the constant, c1 the double nearest what c0 leaves, and so on.
// Nothing checked that, and the tables had drifted: last components up to 19 units off, and a
// pi/3 accurate to double precision only (#1849).
//
// The tables are generated by the number system itself, from the ~340-digit references of
// math/constants/reference_constants.hpp, and VerifyConstantTable() makes certain of it three ways:
//
//   generated   the entry is the type's own parse of the reference, component for component.
//               PrintConstantTable() prints a table that way: it is the generator, see
//               tools/generators/multidouble_constants_gen.cpp.
//   nearest     the entry is the nearest expansion of the reference, certified by efloat at 1024
//               bits, which rounds each residual to a double on its own: the check does not rest
//               on the type's parse being right.
//   computed    the type's own arithmetic and math functions compute the constant -- 4 atan(1),
//               exp(1), log(2), sqrt(5), ... -- to within 2^-(53 limbs - slack) of it. The
//               functions round each operation, so the computed value can sit a few units of the
//               last component off the nearest expansion; the slack is measured per type.
#include <array>
#include <cmath>
#include <cstdio>
#include <iostream>
#include <string>
#include <string_view>
#include <math/constants/reference_constants.hpp>
#include <universal/number/efloat/efloat.hpp>

namespace sw { namespace universal { namespace multidouble_verification {

	// the constants the tables hold
	enum class constant_id {
		pi, pi_2, pi_3, pi_4, two_pi, three_pi_4, inv_pi, two_inv_pi,
		e, inv_e, phi, inv_phi,
		sqrt2, sqrt3, sqrt5, inv_sqrt2,
		ln2, ln10, log2e, log2_10, log10e, log10_2,
		two_over_sqrt_pi
	};

	// the reference digits of a constant
	inline constexpr std::string_view reference_digits(constant_id id) {
		switch (id) {
		case constant_id::pi:               return s_pi;
		case constant_id::pi_2:             return s_pi_2;
		case constant_id::pi_3:             return s_pi_3;
		case constant_id::pi_4:             return s_pi_4;
		case constant_id::two_pi:           return s_two_pi;
		case constant_id::three_pi_4:       return s_three_pi_4;
		case constant_id::inv_pi:           return s_inv_pi;
		case constant_id::two_inv_pi:       return s_two_inv_pi;
		case constant_id::e:                return s_e;
		case constant_id::inv_e:            return s_inv_e;
		case constant_id::phi:              return s_phi;
		case constant_id::inv_phi:          return s_inv_phi;
		case constant_id::sqrt2:            return s_sqrt2;
		case constant_id::sqrt3:            return s_sqrt3;
		case constant_id::sqrt5:            return s_sqrt5;
		case constant_id::inv_sqrt2:        return s_inv_sqrt2;
		case constant_id::ln2:              return s_ln2;
		case constant_id::ln10:             return s_ln10;
		case constant_id::log2e:            return s_log2e;
		case constant_id::log2_10:          return s_log2_10;
		case constant_id::log10e:           return s_log10e;
		case constant_id::log10_2:          return s_log10_2;
		case constant_id::two_over_sqrt_pi: return s_two_over_sqrt_pi;
		}
		return {};
	}

	// the constant computed with Real's own arithmetic and math functions
	template<typename Real>
	Real computed_constant(constant_id id) {
		const Real one(1), two(2), three(3), four(4), five(5), ten(10);
		switch (id) {
		case constant_id::pi:               return four * atan(one);
		case constant_id::pi_2:             return two * atan(one);
		case constant_id::pi_3:             return four * atan(one) / three;
		case constant_id::pi_4:             return atan(one);
		case constant_id::two_pi:           return four * two * atan(one);
		case constant_id::three_pi_4:       return three * atan(one);
		case constant_id::inv_pi:           return one / (four * atan(one));
		case constant_id::two_inv_pi:       return one / (two * atan(one));
		case constant_id::e:                return exp(one);
		case constant_id::inv_e:            return exp(-one);
		case constant_id::phi:              return (one + sqrt(five)) / two;
		case constant_id::inv_phi:          return (sqrt(five) - one) / two;
		case constant_id::sqrt2:            return sqrt(two);
		case constant_id::sqrt3:            return sqrt(three);
		case constant_id::sqrt5:            return sqrt(five);
		case constant_id::inv_sqrt2:        return sqrt(two) / two;
		case constant_id::ln2:              return log(two);
		case constant_id::ln10:             return log(ten);
		case constant_id::log2e:            return one / log(two);
		case constant_id::log2_10:          return log(ten) / log(two);
		case constant_id::log10e:           return one / log(ten);
		case constant_id::log10_2:          return log(two) / log(ten);
		case constant_id::two_over_sqrt_pi: return two / sqrt(four * atan(one));
		}
		return Real(0);
	}

	// one entry of a type's table: its name, its value, and the constant it holds
	template<typename Real>
	struct table_entry {
		const char* name;
		Real        value;
		constant_id id;
	};

	using oracle = efloat<32>;   // 1024 bits

	inline oracle reference_value(constant_id id) {
		oracle r;
		parse(std::string(reference_digits(id)), r);
		return r;
	}

	// whether c[0..n) is the nearest expansion of the reference: c[k] the double nearest the
	// reference less c[0..k), each residual exact at 1024 bits and rounded to a double by efloat
	inline bool is_nearest_expansion(const double* c, int n, constant_id id) {
		oracle rest = reference_value(id);
		for (int k = 0; k < n; ++k) {
			if (double(rest) != c[k]) return false;
			rest -= oracle(c[k]);
		}
		return true;
	}

	// log2 of the relative error of the expansion c[0..n) against the reference (-inf when exact)
	inline double rel_error_log2(const double* c, int n, constant_id id) {
		const oracle ref = reference_value(id);
		oracle d = ref;
		for (int k = 0; k < n; ++k) d -= oracle(c[k]);
		if (d.iszero()) return -INFINITY;
		return std::log2(std::fabs(double(d / ref)));
	}

	template<typename Real>
	void components(const Real& v, double* c, int limbs) {
		for (int k = 0; k < limbs; ++k) c[k] = double(v[k]);
	}

	// tag: the type's name; limbs: the doubles it holds; slack: the bits its own functions may lose
	// on a constant; worst: if not null, the largest log2 relative error of a computed constant
	template<typename Real, std::size_t M>
	int VerifyConstantTable(const std::string& tag, const std::array<table_entry<Real>, M>& table, int limbs, int slack,
	                        bool reportTestCases, double* worst = nullptr) {
		int fails = 0;
		double maxerr = -INFINITY;
		const double limit = -(53.0 * limbs - slack);
		for (const auto& entry : table) {
			double stored[4]{}, parsed[4]{}, computed[4]{};
			components(entry.value, stored, limbs);
			components(Real(std::string(reference_digits(entry.id))), parsed, limbs);
			components(computed_constant<Real>(entry.id), computed, limbs);

			bool generated = true;
			for (int k = 0; k < limbs; ++k) generated = generated && (stored[k] == parsed[k]);
			if (!generated) {
				++fails;
				if (reportTestCases) {
					std::cerr << "FAIL: " << tag << ' ' << entry.name << " is not the type's parse of its reference:";
					for (int k = 0; k < limbs; ++k) { char b[40]; std::snprintf(b, sizeof(b), " %a/%a", stored[k], parsed[k]); std::cerr << b; }
					std::cerr << '\n';
				}
			}
			if (!is_nearest_expansion(stored, limbs, entry.id)) {
				++fails;
				if (reportTestCases) std::cerr << "FAIL: " << tag << ' ' << entry.name << " is not the nearest expansion of its reference\n";
			}
			// a NaN result is a failure, not a comparison that comes out false; -inf is exact
			const double err = rel_error_log2(computed, limbs, entry.id);
			const bool   nan = std::isnan(err);
			if (nan || err > maxerr) maxerr = nan ? INFINITY : err;
			if (nan || err > limit) {
				++fails;
				if (reportTestCases) {
					std::cerr << "FAIL: " << tag << ' ' << entry.name << " computed by the type: relative error 2^" << err
					          << ", above the bound 2^" << limit << '\n';
				}
			}
		}
		if (worst != nullptr) *worst = maxerr;
		return fails;
	}

	// the table as the type's own parse of the references: one line per entry, the components
	// printed with 17 significant digits, which read back as the same doubles
	template<typename Real, std::size_t M>
	void PrintConstantTable(const char* type, const std::array<table_entry<Real>, M>& table, int limbs) {
		for (const auto& entry : table) {
			double c[4]{};
			components(Real(std::string(reference_digits(entry.id))), c, limbs);
			std::printf("constexpr %s %-12s(", type, entry.name);
			for (int k = 0; k < limbs; ++k) std::printf("%s%.17g", (k == 0 ? "" : ", "), c[k]);
			std::printf(");\n");
		}
	}

}}}  // namespace sw::universal::multidouble_verification
