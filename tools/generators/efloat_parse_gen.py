# Writes include/sw/universal/verification/efloat_parse_vectors.hpp: a precision in bits, a
# decimal literal, and the literal rounded to that precision by round-to-nearest-even, as a
# sign, the binary scale of the leading bit, and the mantissa in hex, MSB first.
#
# The rounding is exact: each literal becomes a Fraction and is rounded by integer arithmetic,
# so the reference does not depend on any decimal-to-binary converter. mpmath only supplies
# the digits of the long constants.
#
# Usage:  python3 tools/generators/efloat_parse_gen.py > include/sw/universal/verification/efloat_parse_vectors.hpp
#
# Not run during the build; the output is checked in.
from decimal import Decimal, getcontext
from fractions import Fraction

import mpmath
from mpmath import mp

mp.prec = 8000
getcontext().prec = 10000

PRECISIONS = [608, 2048]


def digits_of(value, n):
    """the first n significant digits of value, as a fixed-point literal"""
    return mpmath.nstr(value, n, strip_zeros=False, min_fixed=-10**6, max_fixed=10**6)


def exact_decimal(f):
    """the exact decimal expansion of a dyadic Fraction"""
    neg = f < 0
    f = abs(f)
    den = f.denominator
    k = den.bit_length() - 1
    assert den == 1 << k
    scaled = f.numerator * 5**k             # f = scaled / 10^k
    s = str(scaled).rjust(k + 1, "0")
    text = s[:len(s) - k] + ("." + s[len(s) - k:] if k > 0 else "")
    return ("-" if neg else "") + text


def round_rne(f, p):
    """round Fraction f to p bits: (negative, scale, mantissa integer with p bits)"""
    neg = f < 0
    f = abs(f)
    e = f.numerator.bit_length() - f.denominator.bit_length()
    if Fraction(2)**e > f:
        e -= 1
    assert Fraction(2)**e <= f < Fraction(2)**(e + 1)
    scaled = f * Fraction(2)**(p - 1 - e)
    m = scaled.numerator // scaled.denominator
    rem = scaled - m
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and m % 2 == 1):
        m += 1
    if m == 1 << p:
        m >>= 1
        e += 1
    return neg, e, m


def midpoint_cases(p):
    """literals at, just above and just below the midpoint of two p-bit neighbours"""
    out = []
    for lead, scale in ((0b1011, -3), (0b1101, 40)):
        for parity in (0, 1):
            # an arbitrary p-bit mantissa with the requested parity of its last bit
            m = (lead << (p - 4)) | (0x5A5A5A5A5A5A5A5A5A5A5A5A5A5A5A5A % (1 << (p - 4)))
            m = (m & ~1) | parity
            mid = (Fraction(2 * m + 1) / Fraction(2)**p) * Fraction(2)**scale
            text = exact_decimal(mid)
            out.append(("midpoint, ties to even", text))
            # one more digit past the exact expansion moves it off the midpoint, by an amount
            # the converter only sees if it looks at every digit
            out.append(("just above the midpoint", text + "000001"))
            # and just below: the expansion minus one unit in a place past its last digit
            places = len(text.split(".")[1]) + 6
            below = Decimal(text) - Decimal(1).scaleb(-places)
            out.append(("just below the midpoint", format(below, "f")))
    return out


def cases():
    out = []
    rsqrt2 = 1 / mpmath.sqrt(2)
    pi = mpmath.pi
    for n in (20, 300, 600, 1200, 2500):
        out.append((f"1/sqrt(2), {n} digits", digits_of(rsqrt2, n)))
    out.append(("-pi, 1200 digits", "-" + digits_of(pi, 1200)))
    out.append(("pi, 1200 digits, scientific", mpmath.nstr(pi * mpmath.mpf(10)**-150, 1200, strip_zeros=False, min_fixed=1, max_fixed=0)))
    out.append(("e, 700 digits, large exponent", mpmath.nstr(mpmath.e * mpmath.mpf(10)**200, 700, strip_zeros=False, min_fixed=1, max_fixed=0)))
    out.append(("leading zeros, 900 digits", "0." + "0" * 400 + digits_of(rsqrt2, 900)[2:]))
    out.append(("trailing zeros", digits_of(pi, 400) + "0" * 3000))
    return out


def scan_value(text):
    return Fraction(Decimal(text))


def hexdigits(m, p):
    width = (p + 3) // 4
    return format(m << (4 * width - p), "0{}x".format(width))


def chunks(s, n=120):
    return [s[i:i + n] for i in range(0, len(s), n)]


def main():
    print("#pragma once")
    print("// efloat_parse_vectors.hpp: correctly rounded references for efloat's parse of long literals (#1713)")
    print("//")
    print("// Copyright (C) 2017 Stillwater Supercomputing, Inc.")
    print("// SPDX-License-Identifier: MIT")
    print("//")
    print("// This file is part of the universal numbers project, which is released under an MIT Open Source license.")
    print("//")
    print("// GENERATED by tools/generators/efloat_parse_gen.py: exact rational rounding, do not edit.")
    print()
    print("#include <cstdint>")
    print()
    print("namespace sw { namespace universal { namespace efloat_parse_verification {")
    print()
    print("struct ParseVector {")
    print("\tconst char*  label;")
    print("\tunsigned     precision;   // bits")
    print("\tconst char*  literal;")
    print("\tbool         negative;")
    print("\tstd::int64_t scale;       // binary exponent of the leading bit")
    print("\tconst char*  mantissa;    // hex, MSB first, padded with zero bits to a whole digit")
    print("};")
    print()
    print("constexpr ParseVector parse_vectors[] = {")
    for p in PRECISIONS:
        for label, text in cases() + midpoint_cases(p):
            neg, e, m = round_rne(scan_value(text), p)
            print(f'\t{{ "{label}", {p}u,')
            for c in chunks(text):
                print(f'\t  "{c}"')
            print(f'\t  , {"true" if neg else "false"}, {e},')
            for c in chunks(hexdigits(m, p)):
                print(f'\t  "{c}"')
            print("\t},")
    print("};")
    print()
    print("}}}  // namespace sw::universal::efloat_parse_verification")


if __name__ == "__main__":
    main()
