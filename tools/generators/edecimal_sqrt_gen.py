# Writes include/sw/universal/verification/edecimal_sqrt_vectors.hpp: decimal integers n and
# floor(sqrt(n)) from Python's math.isqrt, which is exact for integers of any size.  The
# arguments are seeded random integers of 1 to 400 digits, perfect squares and their
# neighbours (k^2 - 1, k^2, k^2 + 1, where the floor changes), and powers of ten.
#
# Usage:  python3 tools/generators/edecimal_sqrt_gen.py > include/sw/universal/verification/edecimal_sqrt_vectors.hpp
#
# Not run during the build; the output is checked in.
import math
import random
import sys


def main():
    rng = random.Random(1725)
    ns = []
    for _ in range(60):
        d = rng.randint(1, 400)
        ns.append(rng.randint(10 ** (d - 1), 10 ** d - 1))
    for _ in range(20):
        k = rng.randint(10 ** 5, 10 ** rng.randint(6, 150))
        ns += [k * k - 1, k * k, k * k + 1]
    ns += [10 ** e for e in (16, 17, 31, 32, 100, 101, 308, 309, 400)]
    print('#pragma once')
    print('// edecimal_sqrt_vectors.hpp: exact integer square roots (#1725)')
    print('//')
    print('// Copyright (C) 2017 Stillwater Supercomputing, Inc.')
    print('// SPDX-License-Identifier: MIT')
    print('//')
    print('// This file is part of the universal numbers project, which is released under an MIT Open Source license.')
    print('//')
    print('// GENERATED by tools/generators/edecimal_sqrt_gen.py from math.isqrt: do not edit.')
    print()
    print('namespace sw { namespace universal { namespace edecimal_sqrt_verification {')
    print()
    print('struct IsqrtVector { const char* n; const char* root; };')
    print()
    print('constexpr IsqrtVector isqrt_vectors[] = {')
    for n in ns:
        print('\t{ "%d",\n\t  "%d" },' % (n, math.isqrt(n)))
    print('};')
    print()
    print('}}}  // namespace sw::universal::edecimal_sqrt_verification')
    sys.stderr.write('%d vectors\n' % len(ns))


if __name__ == '__main__':
    main()
