# Two outputs, both derived from mpmath at 300 decimal digits:
#
#   constants  include/sw/universal/number/qd/math/constants/qd_special_constants.hpp
#              log(2 pi) / 2, Euler's gamma, 1 / sqrt(pi), the Stirling series
#              coefficients B_2k / (2k (2k - 1)), and the Taylor coefficients of
#              lgamma at 1 and at 2, (-1)^k zeta(k) / k and (-1)^k (zeta(k) - 1) / k.
#              Each is four doubles, written as exact hexadecimal literals: the limbs
#              are peeled off the 300-digit value one double at a time.
#
#   vectors    the reference block of static/highprecision/qd/math/error_and_gamma.cpp:
#              erf, erfc, lgamma and tgamma at a set of arguments, each value as six
#              doubles (~318 bits), well clear of quad-double's 212.
#
# Usage:  python3 tools/generators/qd_special_gen.py constants | vectors
#
# Requires mpmath.  Not run during the build; the outputs are checked in.
import sys
import mpmath as mp

mp.mp.dps = 300

def limbs(v, n):
    out = []
    r = mp.mpf(v)
    for _ in range(n):
        d = float(r)
        out.append(d)
        r -= mp.mpf(d)
    return out

def hexs(ds):
    return ', '.join(d.hex() if d != 0.0 else '0.0' for d in ds)

def qd_literal(v):
    return 'qd(' + hexs(limbs(v, 4)) + ')'

STIRLING_TERMS = 40
TAYLOR_TERMS = 60

def constants():
    print('#pragma once')
    print('// qd_special_constants.hpp: constants of the quad-double error and gamma functions')
    print('//')
    print('// Copyright (C) 2017 Stillwater Supercomputing, Inc.')
    print('// SPDX-License-Identifier: MIT')
    print('//')
    print('// This file is part of the universal numbers project, which is released under an MIT Open Source license.')
    print('//')
    print('// GENERATED by tools/generators/qd_special_gen.py from mpmath at 300 digits: do not edit.')
    print('// Every value is four doubles, peeled off the exact value one at a time.')
    print('')
    print('namespace sw { namespace universal {')
    print('')
    print('// log(2 pi) / 2, Euler\'s gamma, and 1 / sqrt(pi)')
    print('constexpr qd qd_half_log_2pi = ' + qd_literal(mp.log(2 * mp.pi) / 2) + ';')
    print('constexpr qd qd_euler_gamma  = ' + qd_literal(mp.euler) + ';')
    print('constexpr qd qd_1_sqrtpi     = ' + qd_literal(1 / mp.sqrt(mp.pi)) + ';')
    print('')
    print('// the Stirling series of lgamma: B_2k / (2k (2k - 1)), k = 1, 2, ...')
    print('constexpr int qd_stirling_terms = %d;' % STIRLING_TERMS)
    print('constexpr qd qd_stirling[qd_stirling_terms] = {')
    for k in range(1, STIRLING_TERMS + 1):
        print('\t' + qd_literal(mp.bernoulli(2 * k) / (2 * k * (2 * k - 1))) + ',')
    print('};')
    print('')
    print('// lgamma(1 + e) = -gamma e + sum_k a_k e^k and lgamma(2 + e) = (1 - gamma) e + sum_k b_k e^k,')
    print('// a_k = (-1)^k zeta(k) / k, b_k = (-1)^k (zeta(k) - 1) / k; index 0 is k = 2')
    print('constexpr int qd_lgamma_taylor_terms = %d;' % (TAYLOR_TERMS - 1))
    print('constexpr qd qd_lgamma_taylor_at_1[qd_lgamma_taylor_terms] = {')
    for k in range(2, TAYLOR_TERMS + 1):
        print('\t' + qd_literal((-1) ** k * mp.zeta(k) / k) + ',')
    print('};')
    print('constexpr qd qd_lgamma_taylor_at_2[qd_lgamma_taylor_terms] = {')
    for k in range(2, TAYLOR_TERMS + 1):
        print('\t' + qd_literal((-1) ** k * (mp.zeta(k) - 1) / k) + ',')
    print('};')
    print('')
    print('}} // namespace sw::universal')

def vectors():
    args = []
    for v in ['-6.5', '-3.25', '-2.4570713', '-1.5', '-0.75', '-0.3', '-1e-20', '1e-30', '1e-8', '0.001953125',
              '0.03125', '0.25', '0.5', '0.9', '0.99999', '1', '1.00001', '1.0625', '1.5', '1.9999', '2', '2.0001',
              '2.5', '2.75', '3', '3.5', '4', '5.5', '6.25', '8', '10', '12.5', '17', '25', '29.5', '30.5', '40',
              '64', '100.25', '170.5']:
        args.append(v)
    print('// GENERATED by tools/generators/qd_special_gen.py vectors: x, then each function as six doubles')
    print('// (an empty entry where the function is not finite there)')
    for v in args:
        x = mp.mpf(float(v))      # the double nearest the literal is the argument
        def six(f):
            try:
                y = f(x)
                if not mp.isfinite(y): return '{}'
                return '{ ' + hexs(limbs(y, 6)) + ' }'
            except Exception:
                return '{}'
        print('\t{ %s,' % float(x).hex())
        print('\t  %s,' % six(mp.erf))
        print('\t  %s,' % six(mp.erfc))
        print('\t  %s,' % six(lambda t: mp.log(abs(mp.gamma(t))) if not (t <= 0 and t == mp.floor(t)) else mp.inf))
        print('\t  %s },' % six(lambda t: mp.gamma(t) if not (t <= 0 and t == mp.floor(t)) else mp.inf))

if __name__ == '__main__':
    what = sys.argv[1] if len(sys.argv) > 1 else ''
    if what == 'constants': constants()
    elif what == 'vectors': vectors()
    else:
        print(__doc__ if __doc__ else 'usage: qd_special_gen.py constants | vectors')
        sys.exit(1)
