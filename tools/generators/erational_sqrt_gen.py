# Writes include/sw/universal/verification/erational_sqrt_vectors.hpp: reduced rationals p/q,
# a precision in bits, and sqrt(p/q) as a reduced rational num/den, computed with Python's
# exact integers:
#
#   - when p and q are perfect squares, the exact root isqrt(p)/isqrt(q);
#   - otherwise the nearest multiple of 2^-k to sqrt(p/q), ties to even, where
#     k = bits - 1 - floor(floor(log2(p/q)) / 2), so the result carries `bits` significant
#     bits.  floor(log2) comes from exact bit lengths and floor(sqrt) from math.isqrt.
#
# Usage:  python3 tools/generators/erational_sqrt_gen.py > include/sw/universal/verification/erational_sqrt_vectors.hpp
#
# Not run during the build; the output is checked in.
import math
import random
import sys
from fractions import Fraction


def floor_log2(p, q):
    e = p.bit_length() - q.bit_length()
    if (p < q * 2 ** e) if e >= 0 else (p * 2 ** -e < q):
        e -= 1
    return e


def rational_sqrt(p, q, bits):
    rp, rq = math.isqrt(p), math.isqrt(q)
    if rp * rp == p and rq * rq == q:
        return Fraction(rp, rq)
    k = bits - 1 - (floor_log2(p, q) // 2)
    A, B = (p * 4 ** k, q) if k >= 0 else (p, q * 4 ** -k)
    R = math.isqrt(A // B)
    lhs, rhs = 4 * A, (2 * R + 1) ** 2 * B
    if rhs < lhs or (rhs == lhs and R % 2 == 1):
        R += 1
    return Fraction(R, 2 ** k) if k >= 0 else Fraction(R * 2 ** -k)


def main():
    rng = random.Random(1725)
    cases = []
    for bits in (1, 2, 10, 53, 106, 200):
        for _ in range(10):
            p = rng.randint(1, 10 ** rng.randint(1, 60))
            q = rng.randint(1, 10 ** rng.randint(1, 60))
            g = math.gcd(p, q)
            cases.append((p // g, q // g, bits))
    for _ in range(8):                                   # rational roots
        a, b = rng.randint(1, 10 ** 20), rng.randint(1, 10 ** 20)
        g = math.gcd(a, b)
        cases.append(((a // g) ** 2, (b // g) ** 2, 106))
    cases += [(2, 1, 106), (1, 3, 20), (1, 10 ** 40, 106), (10 ** 40 + 1, 1, 106), (3, 4, 53)]
    print('#pragma once')
    print('// erational_sqrt_vectors.hpp: square roots of rationals (#1725)')
    print('//')
    print('// Copyright (C) 2017 Stillwater Supercomputing, Inc.')
    print('// SPDX-License-Identifier: MIT')
    print('//')
    print('// This file is part of the universal numbers project, which is released under an MIT Open Source license.')
    print('//')
    print('// GENERATED by tools/generators/erational_sqrt_gen.py with exact integers: do not edit.')
    print()
    print('namespace sw { namespace universal { namespace erational_sqrt_verification {')
    print()
    print('struct RationalSqrtVector { const char* p; const char* q; unsigned bits; const char* num; const char* den; };')
    print()
    print('constexpr RationalSqrtVector rational_sqrt[] = {')
    for p, q, bits in cases:
        r = rational_sqrt(p, q, bits)
        print('\t{ "%d", "%d", %d,\n\t  "%d", "%d" },' % (p, q, bits, r.numerator, r.denominator))
    print('};')
    print()
    print('}}}  // namespace sw::universal::erational_sqrt_verification')
    sys.stderr.write('%d vectors\n' % len(cases))


