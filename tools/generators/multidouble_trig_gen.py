# Writes include/sw/universal/verification/multidouble_trig_vectors.hpp.  Each vector is an
# argument x given as n nonoverlapping doubles (n = 1 to 4; a type with fewer limbs skips it)
# and sin x, cos x and tan x from mpmath at 3200 bits, each as four doubles peeled off the exact
# value, every limb the remainder rounded once.  The arguments:
#
#   - doubles across the whole range, to DBL_MAX, and seeded random ones over every binade;
#   - 6381956970095103 2^797, the double closest to a multiple of pi/2 (Kahan and McDonald),
#     and the doubles nearest small multiples of pi/2;
#   - k pi/2 rounded to 2, 3 and 4 limbs, whose sine or cosine is a few ulps of the type: the
#     reduction must deliver the distance to the multiple to full precision.
#
# The doubles are written as hexadecimal literals; Python's float() of an mpf is correctly
# rounded, so each limb is the remainder rounded once.
#
# Usage:  python3 tools/generators/multidouble_trig_gen.py > include/sw/universal/verification/multidouble_trig_vectors.hpp
#
# Requires mpmath.  Not run during the build; the output is checked in.
import random
import sys
import mpmath as mp

mp.mp.prec = 3200
DBL_MAX = mp.mpf(2) ** 1023 * (2 - mp.mpf(2) ** -52)


def peel(v, n):
    out = []
    r = mp.mpf(v)
    for _ in range(n):
        d = float(r) if r != 0 else 0.0
        out.append(d)
        r -= mp.mpf(d)
    return out


def hexd(d):
    return d.hex() if d != 0.0 else '0.0'


def main():
    rng = random.Random(1723)
    args = []                                    # lists of limbs
    for x in [0.5, 1.0, 2.5, 3.0, 10.0, 100.0, 355.0, 1.0e5, 2.0 ** 30, 1.0e10, 1.0e15, 1.0e16,
              1.0e20, 1.0e22, 1.0e30, 1.0e50, 1.0e80, 1.0e100, 1.0e150, 1.0e200, 1.0e250,
              1.0e300, 2.0 ** 1023, float(DBL_MAX)]:
        args += [[x], [-x]]
    args.append([6381956970095103.0 * 2.0 ** 797])
    for k in [1, 2, 3, 4, 7, 100, 10 ** 6]:
        args.append([float(k * mp.pi / 2)])
    for _ in range(24):
        args.append([rng.uniform(1.0, 2.0) * 2.0 ** rng.randint(0, 1023) * rng.choice([1.0, -1.0])])
    for n in (2, 3, 4):
        for k in [1, 2, 3, 4, 1000, 2 ** 40 + 1]:
            args.append(peel(k * mp.pi / 2, n))
        args.append(peel(-3 * mp.pi / 2, n))
        args.append(peel(mp.mpf(10) ** 30 + mp.sqrt(2), n))
        args.append(peel(mp.mpf(10) ** 300 * mp.e, n))

    print('#pragma once')
    print('// multidouble_trig_vectors.hpp: sin, cos and tan at large arguments and near multiples of pi/2 (#1723)')
    print('//')
    print('// Copyright (C) 2017 Stillwater Supercomputing, Inc.')
    print('// SPDX-License-Identifier: MIT')
    print('//')
    print('// This file is part of the universal numbers project, which is released under an MIT Open Source license.')
    print('//')
    print('// GENERATED by tools/generators/multidouble_trig_gen.py from mpmath at %d bits: do not edit.' % mp.mp.prec)
    print('// x: the argument as n nonoverlapping doubles; sin, cos, tan: four peeled doubles each.')
    print()
    print('namespace sw { namespace universal { namespace multidouble_verification {')
    print()
    print('struct TrigVector { int n; double x[4]; double sin[4]; double cos[4]; double tan[4]; };')
    print()
    print('constexpr TrigVector trig_vectors[] = {')
    for limbs in args:
        x = mp.fsum(mp.mpf(d) for d in limbs)
        xs = limbs + [0.0] * (4 - len(limbs))
        cols = [peel(f(x), 4) for f in (mp.sin, mp.cos, mp.tan)]
        print('\t{ %d, { %s }, { %s }, { %s }, { %s } },' % (
            len(limbs), ', '.join(hexd(d) for d in xs), *(', '.join(hexd(d) for d in c) for c in cols)))
    print('};')
    print()
    print('}}}  // namespace sw::universal::multidouble_verification')
    sys.stderr.write('%d vectors\n' % len(args))


if __name__ == '__main__':
    main()
