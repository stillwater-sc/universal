# Writes include/sw/universal/verification/cascade_exp_range_vectors.hpp: for doubles x near
# the overflow threshold ln(DBL_MAX) = 709.78 and the underflow thresholds ln(DBL_MIN) =
# -708.40 and ln(2^-1075) = -745.13, the value e^x from mpmath at 700 bits, as
#
#   rounded   the correctly rounded double: +inf past DBL_MAX, a subnormal or 0 below DBL_MIN
#   limbs     e^x as four doubles peeled off the exact value, each correctly rounded, so a
#             test can measure a dd_cascade, td_cascade or qd_cascade result at its own
#             precision; all zero when e^x is not a normal double
#
# The doubles are written as hexadecimal literals.  Python's float(str) is correctly rounded,
# subnormals included, so each limb is the decimal expansion of the remaining value rounded
# once.
#
# Usage:  python3 tools/generators/cascade_exp_range_gen.py > include/sw/universal/verification/cascade_exp_range_vectors.hpp
#
# Requires mpmath.  Not run during the build; the output is checked in.
import random
import sys
import mpmath as mp

mp.mp.prec = 700
DBL_MAX = mp.mpf(2) ** 1023 * (2 - mp.mpf(2) ** -52)
DBL_MIN = mp.mpf(2) ** -1022


def rounded(v):
    """v rounded once to a double, +inf past DBL_MAX (round to nearest, overflow threshold
    (2 - 2^-53) 2^1023)"""
    if v >= mp.mpf(2) ** 1023 * (2 - mp.mpf(2) ** -53):
        return float('inf')
    return float(mp.nstr(v, 60, strip_zeros=False))


def limbs(v):
    out = []
    r = v
    for _ in range(4):
        d = float(mp.nstr(r, 60, strip_zeros=False)) if r != 0 else 0.0
        out.append(d)
        r -= mp.mpf(d)
    return out


def hexd(d):
    if d == float('inf'):
        return 'inf_'
    return d.hex() if d != 0.0 else '0.0'


def main():
    rng = random.Random(1709)
    ln_max = mp.log(DBL_MAX)
    xs = [700.0, 708.0, 708.9, 709.0, 709.25, 709.5, 709.75, 709.78, 709.782,
          float(ln_max), float(ln_max) + 2.0 ** -40, 709.7828, 709.79, 709.8, 710.0,
          -700.0, -708.0, float(mp.log(DBL_MIN)), -708.5, -709.0, -720.0, -740.0, -744.0,
          float(mp.log(mp.mpf(2) ** -1074)), -744.6, -745.0, -745.1, float(mp.log(mp.mpf(2) ** -1075)),
          -745.14, -745.2, -750.0]
    xs += [rng.uniform(708.4, 709.78) for _ in range(12)]
    xs += [rng.uniform(-745.13, -708.4) for _ in range(12)]
    print('#pragma once')
    print('// cascade_exp_range_vectors.hpp: exp at the ends of the double range (#1709)')
    print('//')
    print('// Copyright (C) 2017 Stillwater Supercomputing, Inc.')
    print('// SPDX-License-Identifier: MIT')
    print('//')
    print('// This file is part of the universal numbers project, which is released under an MIT Open Source license.')
    print('//')
    print('// GENERATED by tools/generators/cascade_exp_range_gen.py from mpmath at %d bits: do not edit.' % mp.mp.prec)
    print('// rounded: e^x rounded once to a double (+inf, a subnormal or 0 where that is the answer);')
    print('// limbs: e^x as four peeled doubles, all zero when e^x is not a normal double.')
    print('#include <limits>')
    print()
    print('namespace sw { namespace universal { namespace cascade_exp_verification {')
    print()
    print('constexpr double inf_ = std::numeric_limits<double>::infinity();')
    print()
    print('struct ExpVector { double x; double rounded; double limbs[4]; };')
    print()
    print('constexpr ExpVector exp_range[] = {')
    for x in xs:
        v = mp.exp(mp.mpf(x))
        r = rounded(v)
        ls = limbs(v) if DBL_MIN <= v <= DBL_MAX else [0.0, 0.0, 0.0, 0.0]
        print('\t{ %s, %s, { %s } },' % (hexd(x), hexd(r), ', '.join(hexd(d) for d in ls)))
    print('};')
    print()
    print('}}}  // namespace sw::universal::cascade_exp_verification')
    sys.stderr.write('%d vectors\n' % len(xs))


if __name__ == '__main__':
    main()
