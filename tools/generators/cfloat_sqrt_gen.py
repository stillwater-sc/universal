# Writes include/sw/universal/verification/cfloat_sqrt_vectors.hpp: positive quad encodings a
# (normals across the whole exponent range, subnormals, and the extremes) and the encoding of
# sqrt(a) rounded once to 113 bits, ties to even, from mpmath at 1000 bits.  Each encoding is
# two 64-bit words, high first.  A cfloat with fbits > 52 cannot take the host shortcut, so
# these exercise the Newton iteration and its final correction.
#
# Usage:  python3 tools/generators/cfloat_sqrt_gen.py > include/sw/universal/verification/cfloat_sqrt_vectors.hpp
#
# Requires mpmath.  Not run during the build; the output is checked in.
import random
import sys
import mpmath as mp

FBITS, ES = 112, 15
BIAS = (1 << (ES - 1)) - 1
EMIN = 1 - BIAS


def decode(bits):
    e = (bits >> FBITS) & ((1 << ES) - 1)
    f = bits & ((1 << FBITS) - 1)
    if e == 0:
        return mp.mpf(f) * mp.mpf(2) ** (EMIN - FBITS)
    return mp.mpf((1 << FBITS) | f) * mp.mpf(2) ** (e - BIAS - FBITS)


def encode(v):
    # v > 0 is a normal quad value with at most 113 significant bits
    m, e = mp.frexp(v)                      # v = m 2^e, m in [0.5, 1)
    sig = int(mp.ldexp(m, FBITS + 1))       # 113-bit integer, exact
    E = e - 1 + BIAS
    assert 0 < E < (1 << ES) - 1 and sig >> FBITS == 1
    return (E << FBITS) | (sig & ((1 << FBITS) - 1))


def rounded_sqrt(v):
    with mp.workprec(FBITS + 1):            # mpmath's sqrt is correctly rounded, to nearest even
        return +mp.sqrt(v)


def main():
    mp.mp.prec = 1000
    rng = random.Random(1725)
    args = []
    for _ in range(160):                    # normals, every binade equally likely
        e = rng.randint(1, (1 << ES) - 2)
        args.append((e << FBITS) | rng.getrandbits(FBITS))
    for _ in range(24):                     # subnormals
        args.append(rng.getrandbits(FBITS) >> rng.randint(0, FBITS - 1) or 1)
    args += [1, (1 << FBITS) - 1, 1 << FBITS,                         # smallest, largest subnormal, smallest normal
             (((1 << ES) - 2) << FBITS) | ((1 << FBITS) - 1),         # maxpos
             BIAS << FBITS, (BIAS << FBITS) | 1, ((BIAS + 1) << FBITS) | ((1 << FBITS) - 1)]   # 1, 1 + ulp, 4 - ulp
    print('#pragma once')
    print('// cfloat_sqrt_vectors.hpp: correctly rounded sqrt of IEEE quad encodings (#1725)')
    print('//')
    print('// Copyright (C) 2017 Stillwater Supercomputing, Inc.')
    print('// SPDX-License-Identifier: MIT')
    print('//')
    print('// This file is part of the universal numbers project, which is released under an MIT Open Source license.')
    print('//')
    print('// GENERATED by tools/generators/cfloat_sqrt_gen.py from mpmath at %d bits: do not edit.' % mp.mp.prec)
    print('// a and sqrt(a) as cfloat<128,15> encodings, two 64-bit words each, high word first.')
    print('#include <cstdint>')
    print()
    print('namespace sw { namespace universal { namespace cfloat_sqrt_verification {')
    print()
    print('struct QuadSqrtVector { std::uint64_t a[2]; std::uint64_t r[2]; };')
    print()
    print('constexpr QuadSqrtVector quad_sqrt[] = {')
    for a in args:
        r = encode(rounded_sqrt(decode(a)))
        print('\t{ { 0x%016Xull, 0x%016Xull }, { 0x%016Xull, 0x%016Xull } },' % (a >> 64, a & (2**64 - 1), r >> 64, r & (2**64 - 1)))
    print('};')
    print()
    print('}}}  // namespace sw::universal::cfloat_sqrt_verification')
    sys.stderr.write('%d vectors\n' % len(args))


if __name__ == '__main__':
    main()
