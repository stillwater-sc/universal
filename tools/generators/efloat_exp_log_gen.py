# Writes include/sw/universal/verification/efloat_exp_log_vectors.hpp: a function name, its
# arguments as doubles (exact binary values, so the C++ test constructs the same arguments),
# and the function's value from mpmath at 2600 bits, printed to 700 significant digits
# (~2325 bits).  That covers a check at 2048 bits with room to spare.
#
# Usage:  python3 tools/generators/efloat_exp_log_gen.py > include/sw/universal/verification/efloat_exp_log_vectors.hpp
#
# Not run during the build; the output is checked in.
import mpmath
from mpmath import mp, mpf

mp.prec = 2600
DIGITS = 700

FUNCTIONS = {
    "exp":   (1, mpmath.exp),
    "exp2":  (1, lambda x: mpmath.power(2, x)),
    "exp10": (1, lambda x: mpmath.power(10, x)),
    "expm1": (1, mpmath.expm1),
    "log":   (1, mpmath.log),
    "log2":  (1, lambda x: mpmath.log(x, 2)),
    "log10": (1, mpmath.log10),
    "log1p": (1, mpmath.log1p),
    "sinh":  (1, mpmath.sinh),
    "cosh":  (1, mpmath.cosh),
    "tanh":  (1, mpmath.tanh),
    "asinh": (1, mpmath.asinh),
    "acosh": (1, mpmath.acosh),
    "atanh": (1, mpmath.atanh),
    "atan":  (1, mpmath.atan),
    "pow":   (2, mpmath.power),
    "sin":   (1, mpmath.sin),
    "cos":   (1, mpmath.cos),
    "tan":   (1, mpmath.tan),
    "asin":  (1, mpmath.asin),
    "acos":  (1, mpmath.acos),
    "atan2": (2, mpmath.atan2),
}

# arguments are doubles: every one is exactly representable, in Python and in C++
CASES = [
    ("exp", 0.75), ("exp", -37.5), ("exp", 484.25), ("exp", -700.125), ("exp", 0.3466),
    ("exp", 1e-10), ("exp", 2000.25),
    ("exp2", 0.3), ("exp2", -10.75), ("exp2", 100.1),
    ("exp10", 0.3), ("exp10", -5.5), ("exp10", 20.25),
    ("expm1", 0.5), ("expm1", -0.4), ("expm1", 3.0), ("expm1", 0.1), ("expm1", 1e-30),
    ("log", 3.25), ("log", 1e200), ("log", 0.001), ("log", 2.0), ("log", 0.5), ("log", 1.5),
    ("log", 1e-300), ("log", 10.0),
    ("log2", 3.0), ("log2", 1e-100), ("log2", 10.0),
    ("log10", 2.0), ("log10", 7.5e-20), ("log10", 3.0),
    ("log1p", 0.3), ("log1p", -0.3), ("log1p", 0.374), ("log1p", 1e-25), ("log1p", 5.0),
    ("sinh", 0.25), ("sinh", 3.5), ("cosh", 3.5), ("tanh", 0.7),
    ("asinh", 2.5), ("acosh", 3.0), ("atanh", 0.3),
    ("atan", 0.75), ("atan", 0.6), ("atan", 3.0),
    ("pow", 2.5, 0.3333), ("pow", 10.0, -7.25), ("pow", 1.0625, 200.5),
    # the trigonometric functions reduce with pi, which must be carried at the working precision
    ("sin", 10.0), ("sin", 0.5), ("sin", 1e6), ("cos", 10.0), ("cos", 3.0), ("tan", 1.25),
    # the versine kernel (#1756): r below its halving target, r at pi/4, and a cos quadrant
    ("sin", 1e-10), ("cos", 1e-10), ("tan", 3e-7), ("sin", 0.78125), ("cos", -0.78125), ("sin", 1.5), ("tan", -2.75),
    ("asin", 0.5), ("asin", 0.9), ("acos", 0.3), ("acos", -0.95),
    ("atan2", 1.0, -2.0), ("atan2", -3.0, -0.5),
]


def cpp_double(x):
    s = repr(float(x))
    return s if ("e" in s or "." in s or "inf" in s or "nan" in s) else s + ".0"


def main():
    print("#pragma once")
    print("// efloat_exp_log_vectors.hpp: high-precision references for efloat's exp/log family (#1712)")
    print("//")
    print("// Copyright (C) 2017 Stillwater Supercomputing, Inc.")
    print("// SPDX-License-Identifier: MIT")
    print("//")
    print("// This file is part of the universal numbers project, which is released under an MIT Open Source license.")
    print("//")
    print(f"// GENERATED by tools/generators/efloat_exp_log_gen.py with mpmath {mpmath.__version__} at {mp.prec} bits,")
    print(f"// printed to {DIGITS} significant digits: do not edit.")
    print()
    print("namespace sw { namespace universal { namespace efloat_exp_log_verification {")
    print()
    print("struct FunctionVector { const char* function; double x; double y; const char* value; };")
    print()
    print("constexpr FunctionVector function_vectors[] = {")
    for case in CASES:
        name, args = case[0], case[1:]
        arity, f = FUNCTIONS[name]
        assert len(args) == arity, case
        value = f(*[mpf(a) for a in args])
        text = mpmath.nstr(value, DIGITS, strip_zeros=False, min_fixed=1, max_fixed=0)
        y = cpp_double(args[1]) if arity == 2 else "0.0"
        print(f'\t{{ "{name}", {cpp_double(args[0])}, {y},')
        print(f'\t  "{text}" }},')
    print("};")
    print()
    print("}}}  // namespace sw::universal::efloat_exp_log_verification")


if __name__ == "__main__":
    main()
